/*
 * 功能开关配置 —— 各功能点通过宏 + 条件编译控制，方便硬件未就绪时
 * 暂时屏蔽某个功能，而不必改动功能代码本身。
 *
 * 规则：
 *   - 宏为 1 时该功能参与编译；为 0 时功能代码被屏蔽，对外接口
 *     保留桩实现（返回未启用/空值），调用方无需修改。
 */
#pragma once

/* ---------------- 功能 1：TF 卡（SPI 模式） ----------------
 * 2026-11-04：暂时屏蔽 —— 手头暂无 TF 卡，待找到后改回 1 调试。
 * 引脚：CS=IO2 / MOSI=IO11 / SCK=IO12 / MISO=IO13（板载 TF 卡座）
 */
#define APP_ENABLE_TF_CARD   0

/* ---------------- 功能 2：WiFi 配网 ----------------
 * SoftAP ESP32_DEMO + Web 配网（手机连上后浏览器访问任意网址弹出配网页），
 * 凭据优先存 TF 卡（APP_ENABLE_TF_CARD=0 时存 NVS），断线自动重连。
 */
#define APP_ENABLE_WIFI      1

/* ---------------- 功能 3：LED 状态指示（IO1） ----------------
 * 按 readme.txt 要求指示网络状态：
 *   NO_CRED      -> 熄灭
 *   CONNECTING   -> 快闪 2 下（亮100ms/灭100ms/亮100ms）后灭 1s，循环
 *   CONNECTED    -> 慢闪（亮500ms/灭500ms）
 *   INTERNET_OK  -> 常亮
 * 依赖功能 2 的 wifi_mgr_get_state()；APP_ENABLE_WIFI=0 时 LED 仅保持熄灭。
 */
#define APP_ENABLE_LED       1

/* ---------------- 功能 4：LCD 显示（ST7789，0.96 寸 80x160） ----------------
 * 引脚：CS=IO39 / DC=IO40 / RST=IO38 / BL=IO41，数据线 SCLK=IO12 / MOSI=IO11
 * 注意：数据线与 TF 卡共用同一条 SPI2 总线，靠各自 CS 分时复用。
 */
#define APP_ENABLE_LCD       1

/* LCD 纯色刷屏测试开关：
 *   1 = 逐色刷屏测试（红/绿/蓝/白/黑…每 3s 一换），用于验证屏幕与接线；
 *   0 = 正常运行显示界面（东八区时间 + 当前热点名，20fps 刷新）。
 */
#define APP_LCD_COLOR_TEST   0

/* ---------------- 功能 5：ES8388 I2C 扫描（语音翻译机 第 1 步） ----------------
 * 只验证控制通路：初始化 I2C 总线（SDA=IO4/SCL=IO5）并扫描 0x08~0x77，
 * 期望扫到 ES8388 @ 0x10。不写 codec 任何寄存器，不会发出声音。
 * 开机扫描一次，之后每 10s 在主循环里复扫一次，方便观察热插拔/接触不良。
 */
#define APP_ENABLE_I2C_SCAN  1

/* ---------------- 功能 6：ES8388 寄存器读写诊断（语音翻译机 第 4 步） ----------------
 * 三段式验证：复位前 dump（查看残留配置）-> 软复位（R0 bit7 SCPReset）
 * -> 复位后 dump 与默认值比对（证明复位生效）-> 写/回读/还原测试。
 *
 * 为什么每次初始化都要软复位：ES8388 没有硬件复位脚，断电前一直保持
 * 寄存器内容，换固件后残留旧配置（实测到 xiaozhi 的配置还在里面）。
 * 软复位位不自清零，写 0x80 后必须写回 0x06 解除，见 es8388.c。
 *
 * 复位后 DAC 掉电、输出全关、无 MCLK，任何测试都不会发声。
 * 开机跑一次，不进主循环。依赖功能 5 的 codec_bus。
 */
#define APP_ENABLE_CODEC_REGS 1

/* ---------------- 功能 7：I2S 时钟 + 喇叭播放验证（语音翻译机 第 2/3/5 步） ----------------
 * 起独立任务：初始化 I2S（24kHz/16bit/立体声，ESP32 主、codec 从），
 * 软复位并配置 ES8388 播放通路，打开功放（IO42，低电平有效）。
 *
 * 2026-11-10：已验证通过（用户确认听到 440Hz 声音），按需求先关闭，
 * 避免持续发声干扰后续调试。代码保留，需要时改回 1 即可。
 *
 * 排障用法（无声音时按这个顺序开）：
 *   1. APP_ENABLE_AUDIO_TEST=1 + APP_AUDIO_BEEP=0
 *      -> 只有时钟在跑、持续写静音，安静。适合量 MCLK/BCLK/WS 波形。
 *   2. APP_ENABLE_AUDIO_TEST=1 + APP_AUDIO_BEEP=1
 *      -> 每 1.5s 播 440Hz/1.5s 正弦（振幅 50%），听声验证 DAC+功放+喇叭。
 *   3. 两者都开时会打印完整寄存器 dump 和关键位解读
 *      （R0 EnRef / R4 输出使能 / R8 主从 / R19 静音 / 音量），
 *      可直接定位是哪一环没配好。
 *
 * 已知坑（复现时别重踩）：
 *   - R19 bit2 是 DAC 静音位，复位默认带静音，必须显式清
 *   - R0 要写 0x16 而不是 0x12，bit2 EnRef 必须为 1（参考电压使能）
 *   - 功放 IO42 是低电平使能（SPK_EN_ACTIVE_LOW）
 *   - 所有 I2C 配置必须在 i2s_channel_enable() 之前完成
 */
#define APP_ENABLE_AUDIO_TEST 0
#define APP_AUDIO_BEEP        0

/* ---------------- 功能 8：录音 + 回放（BOOT 按键） ----------------
 * 长按 BOOT(>300ms)：进入录音，松开停止。录音期间 LCD 第二行显示录音时长。
 * 短按 BOOT(<300ms)：回放上一段录音。LCD 第二行显示总时长和剩余时长。
 * 两种状态结束或回到空闲后，第二行恢复显示 WiFi 名称。
 *
 * 存储：内存缓冲，单声道 16bit/24kHz（约 48KB/s）。
 *   优先放 PSRAM，不足则降级到内部 RAM 只留 4 秒。
 *   REC_MAX_SECONDS 只在 PSRAM 可用时生效（8MB 可存 170+ 秒，
 *   这里取 60 秒，留足余量给 WiFi/LCD/未来扩展）。
 *
 * 依赖：I2S 必须全双工（TX+RX），且录音/播放同为 24kHz
 *       （ES8388 的 ADC/DAC 共用一对 LRCK，无法分别设采样率）。
 */
#define APP_ENABLE_RECORDER   1

/* 按键识别 */
#define APP_ENABLE_BUTTON     1
#define BTN_LONG_PRESS_MS     300    /* 超过此时长判为长按（录音） */

/* 单段录音上限（秒），仅 PSRAM 可用时按此值 */
#define REC_MAX_SECONDS       60

/* ---------------- 录音音质参数（2026-11-10 加入，解决"录完回放杂音大"） ----------------
 *
 * 实测背景：ADC 原来是 R9=0xBB（厂商 esp_codec_dev 的原始值）。数据手册里
 * MIC PGA 只有 0000~1000 共 9 档（0~+24dB，步进 3dB），0xB 属于未定义档位。
 * 现在改为数据手册内的合法档位，默认 +24dB（0x88），觉得增益过高就往下调。
 *
 *   REC_ADC_PGA_DB   0~24，步进 3。录出来声音太小就加，削顶（日志 clip>1%）就减。
 *   REC_HPF_HZ       一阶高通，切掉直流偏置和低频嗡声（电源/工频/手持风噪）。
 *   REC_LPF_HZ       二阶 Butterworth 低通，压掉语音带外的高频嘶声。
 *   REC_MIC_CHANNEL  取哪一路：0=左右平均（默认），1=只左，2=只右。
 *                    看日志里 L/R 的 rms 差异再决定：两路差不多就保持平均；
 *                    一路明显是噪声（rms 高但没语音）就切到另一路。
 *   REC_STATS_LOG    每次录完打印 L/R/输出三路实测电平，用于验证改动是否有效。
 */
#define REC_ADC_PGA_DB        24
#define REC_HPF_HZ            100
#define REC_LPF_HZ            7000
/* 实测（2026-11-10，+24dB PGA，4.6s 说话）：
 *   L rms=-36.7 peak=-19.5   R rms=-44.8 peak=-25.7   out rms=-47.7
 * L 比 R 高 8dB，说明语音主要从左路进来，右路是衰减/浮空输入。
 * 取平均等于白掺进一路噪声并损失 6dB 信号，所以固定只取 L。 */
#define REC_MIC_CHANNEL       1
#define REC_STATS_LOG         1

/* ---------------- 录音后处理：噪声门 + 峰值归一化 ----------------
 *
 * 为什么需要：上面那组数据里语音峰值只有 -19.5 dBFS，电平太低。
 * 用户为了听清会开大音量，功放和 DAC 的底噪就跟着一起变大——
 * "还剩一点点杂音"就是这么来的。两步处理：
 *
 *   1. 噪声门（REC_GATE_DB）：低于阈值时把增益压到 0，说完了那几秒
 *      彻底安静。门打开后至少维持 REC_GATE_HOLD_MS，避免音节间隙
 *      反复开关（那个听起来就是"哒哒哒"）；增益本身做 5ms 平滑，
 *      不会切出爆音。
 *   2. 峰值归一化（REC_NORMALIZE_DB）：把整段峰值拉到 -3 dBFS，
 *      最多提升 REC_NORMALIZE_MAX_DB。这样回放不需要开大音量。
 *
 * 阈值设 0 表示关闭该功能。如果发现说话开头/结尾被吃掉，
 * 把 REC_GATE_DB 往低调（例如 -50）；如果停顿处仍有杂音，
 * 往高调（例如 -40）。
 */
#define REC_GATE_DB           (-45)
#define REC_NORMALIZE_DB      (-3)
#define REC_NORMALIZE_MAX_DB  18

/* 噪声门保持时间：门打开后至少维持这么久才允许关闭。
 * 没有保持时间的话，语音的音节间隙（几十毫秒）就会让门反复开关，
 * 听感是"哒哒哒"的断续 —— 这一条是专门防这个的。 */
#define REC_GATE_HOLD_MS      200

/* 噪声门前瞻（毫秒）：音频延迟这么久再输出，但判断仍用未延迟的信号，
 * 等于"先看到未来"，门在字头到达时已经开好。
 * 太小（<8ms）字头仍会被吃掉；太大（>20ms）会让人觉得说完的尾音变钝，
 * 而且缓冲吃内存。12ms 覆盖 1ms 包络爬升 + 2ms 增益平滑还有富余。 */
#define REC_GATE_LOOKAHEAD_MS 12

/* 向下扩展比（REC_GATE_RATIO:1）。
 * 这是"字头不被切断"的关键：阈值以下不做硬静音，而是每低 1dB 就多压
 * (ratio-1)dB。ratio 越大越接近硬开关（字头感越强），越小越柔和但底噪漏得多。
 *   3 = 折中选择：低于阈值 10dB 处压 20dB，本底 -63dBFS 处压 36dB（等效静音）
 *   2 = 更柔和，适合嫌字头仍被切
 *   8 = 接近原来的硬门，停顿最干净但字头最明显
 */
#define REC_GATE_RATIO        3

/* ---------------- 脉冲诊断（REC_STATS_LOG 打开时生效） ----------------
 * 录音时逐点检查相邻采样的跳变，超过阈值的点记为一次"脉冲"，
 * 并记录相邻脉冲的间隔。间隔能直接指出元凶：
 *   ~100ms（10Hz）   WiFi beacon 突发
 *   ~50ms （20Hz）   LCD 20fps 刷屏
 *   ~20ms           录音分块边界（本文件 BLOCK 大小）
 *   间隔无规律       DMA 欠载/溢出，随机丢采样
 * 阈值取 12000（约 37% 满量程）：语音的快速变化很少一步跳这么多，
 * 而丢采样造成的台阶通常是上万。
 */
#define REC_CLICK_DIFF        12000

/* ---------------- 开机录音自检（诊断用，定位"哒哒"声来源） ----------------
 * 置 1 时，开机后自动做两段 6 秒静音录音并各打一份电平剖面：
 *   第一段：先 esp_wifi_stop() 关掉射频 -> 剖面里没有干扰就说明是射频
 *   第二段：恢复 WiFi 再录 -> 干扰回来即可确认
 * 两段对比能一次性排除/坐实"射频与网络"这一类嫌疑，剩下的才是
 * 电源、外设 GPIO、环境声。
 *
 * 注意：会让开机流程多等约 18 秒，测完必须改回 0。
 */
#define APP_REC_DIAG_BOOT     0

/* ---------------- WiFi 射频降噪（2026-11-10 实测结论） ----------------
 *
 * 开机 A/B 对照（同样 6 秒静音、PGA +24dB）：
 *   射频关闭：本底 -73 dBFS，无突发
 *   射频开启：本底 -52 dBFS，且每隔约 1s 出现 -40~-30 dBFS 的噪声爆发
 * 结论：录音里那层底噪和"哒哒"声来自 WiFi 射频耦合进模拟通路，
 * 不是麦克风也不是电源。软件上能做的两件事：
 *
 *   APP_WIFI_TX_POWER_QDBM
 *     发射功率上限，单位 0.25dBm。默认 80 = 20dBm（满功率）。
 *     降到 40 = 10dBm 可显著减少耦合；本机实测 RSSI 约 -37dBm，
 *     余量很大，10dBm 完全够用。若部署得远、出现掉线，往回调
 *     （60 = 15dBm，或 80 恢复满功率）。
 *
 *   APP_WIFI_AP_BEACON_TU
 *     自己 SoftAP 的 beacon 间隔，单位 TU（1 TU ≈ 1.024ms），
 *     必须是 100 的整数倍。默认 100 TU ≈ 102ms，也就是每秒发 10 次；
 *     改成 1000 TU ≈ 1.02s 后 AP 自身的发射活动降一个数量级，
 *     手机仍然能正常发现这个热点（只是慢一点点）。
 *
 * 另外听感上"哒哒"比稳定底噪更刺耳：突发会把噪声门顶开，
 * 停顿处反而冒出声音。所以优先降突发，而不是单纯降平均电平。
 */
#define APP_WIFI_TX_POWER_QDBM   40
#define APP_WIFI_AP_BEACON_TU    1000
